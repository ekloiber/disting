#!/usr/bin/env python3
"""
Generate hello_disting_mk4/subBassTables.h: fixed-point lookup tables for the
Sub bass algorithm. Run from the repository root:

    python3 tools/gen_subbass_tables.py

Every table is indexed by a parameter value (0..99) or a phase, so the audio
loop never calls exp(), sin() or pow() at run time.
"""
import math
import os

FS = 75000.0
OUT = os.path.join(os.path.dirname(__file__), '..', 'hello_disting_mk4', 'subBassTables.h')


def q(x, bits):
    v = int(round(x * (1 << bits)))
    return max(-(1 << 31), min((1 << 31) - 1, v))


def table(name, ctype, values, comment, per_line=8):
    lines = [f"// {comment}", f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def attack_seconds(p):
    return 0.0005 * (400.0 ** (p / 99.0))      # 0.5 ms .. 200 ms


def release_seconds(p):
    return 0.010 * (200.0 ** (p / 99.0))       # 10 ms .. 2 s


def hpf_hz(p):
    return 20.0 * (15.0 ** ((p - 1) / 98.0))   # p=1: 20 Hz .. p=99: 300 Hz


def one_pole(seconds):
    return 1.0 - math.exp(-1.0 / (seconds * FS))


def main():
    parts = [
        "// Generated by tools/gen_subbass_tables.py -- do not edit by hand.",
        "#ifndef SUBBASS_TABLES_H",
        "#define SUBBASS_TABLES_H",
        "",
        f"#define SUBBASS_SAMPLE_RATE {int(FS)}",
        "",
        table("kSineQ15", "short",
              [max(-32767, min(32767, int(round(32767 * math.sin(2 * math.pi * i / 256))))) for i in range(257)],
              "sin(2*pi*i/256), Q15, 257 entries (last = first) for interpolation"),
        "",
        table("kExp2Q30", "int",
              [q(2.0 ** (i / 256.0), 30) for i in range(257)],
              "2^(i/256), Q30, 257 entries"),
        "",
        table("kAttackQ31", "int",
              [q(one_pole(attack_seconds(p)), 31) for p in range(100)],
              "envelope attack coefficient 1-exp(-1/(t*fs)), Q31; t = 0.5 ms * 400^(p/99)"),
        "",
        table("kReleaseQ31", "int",
              [q(one_pole(release_seconds(p)), 31) for p in range(100)],
              "envelope release coefficient, Q31; t = 10 ms * 200^(p/99)"),
        "",
        table("kHpfFQ30", "int",
              [0] + [q(2.0 * math.sin(math.pi * hpf_hz(p) / FS), 30) for p in range(1, 100)],
              "state-variable HPF frequency coefficient 2*sin(pi*fc/fs), Q30; p=0 bypass; fc = 20 Hz * 15^((p-1)/98)"),
        "",
        table("kSensQ12", "int",
              [q(2.0 ** ((p - 50) / 12.5), 12) for p in range(100)],
              "envelope gain 2^((p-50)/12.5), Q12; p=50 -> 1.0 (a 5 V envelope gives full sub)"),
        "",
        "// state-variable filter damping 1/Q for Q = 0.7071 (Butterworth), Q30",
        f"#define kHpfDampQ30 ({q(math.sqrt(2.0), 30)})",
        "",
        "// phase increment for C4 (261.6256 Hz) with a 32-bit phase accumulator",
        f"#define kC4PhaseInc ({int(round(261.6255653 / FS * 2 ** 32))})",
        "",
        "#endif // SUBBASS_TABLES_H",
        "",
    ]
    with open(OUT, 'w') as f:
        f.write("\n".join(parts))
    print("wrote", os.path.normpath(OUT))


if __name__ == '__main__':
    main()
